#!/usr/bin/env python3
"""
Writes assets/eng_bdb/corrections-meant.yaml: Hebrew quotations of two
words or more whose words are in a verse near the one cited, and in no
form in the cited verse (decided 2026-11-21; print-checks.md, "Nearby
verses"). The reference stays as BDB printed it; the module links to the
verse the words are in (bn:meant).

    tools/venv/bin/python -I tools/check-bdb-quotations.py report.json
    tools/venv/bin/python -I tools/make-bdb-meant-corrections.py report.json

From the quotation checker's report it takes each "nearby verse" result
whose quotation has two words or more (BDB's abbreviations aside) and
none of whose words is in the cited verse, even with a prefix or suffix,
or spelled with or without vav and yod. Where several verses near the
one cited have the words, the checker gives the nearest, so the verse
meant is the likeliest, not checked in the print. The link's text is
read from the source, where the quotation stands directly before it.
"""
import json
import re
import sys
from pathlib import Path

SOURCE = Path('assets/eng_bdb/source/bdb.json')
OUT = Path('assets/eng_bdb/corrections-meant.yaml')
BOOKS = {
    'Genesis': 'GEN', 'Exodus': 'EXO', 'Leviticus': 'LEV', 'Numbers': 'NUM',
    'Deuteronomy': 'DEU', 'Joshua': 'JOS', 'Judges': 'JDG', 'Ruth': 'RUT',
    'I Samuel': '1SA', 'II Samuel': '2SA', 'I Kings': '1KI', 'II Kings': '2KI',
    'I Chronicles': '1CH', 'II Chronicles': '2CH', 'Ezra': 'EZR',
    'Nehemiah': 'NEH', 'Esther': 'EST', 'Job': 'JOB', 'Psalms': 'PSA',
    'Proverbs': 'PRO', 'Ecclesiastes': 'ECC', 'Song of Songs': 'SNG',
    'Isaiah': 'ISA', 'Jeremiah': 'JER', 'Lamentations': 'LAM',
    'Ezekiel': 'EZK', 'Daniel': 'DAN', 'Hosea': 'HOS', 'Joel': 'JOL',
    'Amos': 'AMO', 'Obadiah': 'OBA', 'Jonah': 'JON', 'Micah': 'MIC',
    'Nahum': 'NAM', 'Habakkuk': 'HAB', 'Zephaniah': 'ZEP', 'Haggai': 'HAG',
    'Zechariah': 'ZEC', 'Malachi': 'MAL',
}
FINALS = str.maketrans('\u05da\u05dd\u05df\u05e3\u05e5', '\u05db\u05de\u05e0\u05e4\u05e6')


def bare(word):
    """Consonants only, final forms as medial, without vav and yod."""
    letters = ''.join(c for c in word if '\u05d0' <= c <= '\u05ea').translate(FINALS)
    return letters.replace('\u05d5', '').replace('\u05d9', '')


def words(text):
    return [bare(w) for w in re.split(r'[\s\u05be\u05c3()\[\]]+', text) if bare(w)]


def quoted(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    report = json.load(open(sys.argv[1], encoding='utf-8'))
    source = {e['rid']: e for e in json.loads(SOURCE.read_text(encoding='utf-8'))}
    out = []
    for r in report:
        if r['result'] != 'nearby verse':
            continue
        quote_words = words(r['quote'])
        if len(quote_words) < 2:
            continue
        cited = words(r['verse'])
        # Any word in the cited verse, in any form: not one for a note.
        if all(any(q in v for v in cited) for q in quote_words if len(q) >= 2):
            continue
        m = re.fullmatch(r'(.+) (\d+):(\d+)', r['detail'])
        if not m or m.group(1) not in BOOKS:
            sys.exit(f"{r['entry']}: verse \"{r['detail']}\" not understood")
        meant = f'{BOOKS[m.group(1)]} {m.group(2)}:{m.group(3)}'
        html = json.dumps(source[r['entry']]['content'], ensure_ascii=False).replace('\\"', '"')
        links = re.findall(r'<span dir="rtl">' + re.escape(r['quote']) + r'</span>\s*<a [^>]*data-ref="' +
                           re.escape(r['ref']) + r'"[^>]*>([^<]*)</a>', html)
        if len(set(links)) != 1:
            sys.exit(f"{r['entry']}: the link after the quotation is not found once ({links})")
        out.append((r['entry'], r['ref'], links[0], meant, r['quote']))
    lines = [
        '# Generated by tools/make-bdb-meant-corrections.py from the quotation',
        "# checker's report; do not edit by hand. Quotations of two words or more",
        '# whose words are in a verse near the one BDB cites, and not in the cited',
        '# verse: kept as printed, linked to the verse the words are in (the nearest',
        '# such verse; not checked in the print).',
        '',
    ]
    for entry, link, text, meant, quote in out:
        lines += [
            f'- entry: {entry}',
            '  kind: meant',
            f'  link: {quoted(link)}',
            f'  text: {quoted(text)}',
            f'  meant: {quoted(meant)}',
            f'  quote: {quoted(quote)}',
            '  evidence: "the quotation\'s words are in this verse, not in the one cited (WLC); not checked in the print"',
        ]
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(out)} references written to {OUT}')


if __name__ == '__main__':
    main()
